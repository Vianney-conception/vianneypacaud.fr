    const inputRecherche = document.querySelector("#ZonedeRecherche input");
    const zoneProposition = document.querySelector(".ZonedeProposition");
    if (!inputRecherche || !zoneProposition) return;
    let listeResultats = zoneProposition.querySelector("ul");
    if (!listeResultats) {
        listeResultats = document.createElement("ul");
        zoneProposition.appendChild(listeResultats);
    }
    zoneProposition.style.display = "none";
    inputRecherche.addEventListener("input", (e) => {
        const valeur = e.target.value.trim();
        if (valeur.length > 0) {
            inputRecherche.classList.add("contient");
        } else {
            inputRecherche.classList.remove("contient");
            listeResultats.innerHTML = "";
            zoneProposition.style.display = "none";
            return;
        }
        const motsRecherche = valeur.toLowerCase().split(/\s+/);
        const resultatsFiltres = elementsRecherche.filter((item) => {
            const nomLower = item.nom.toLowerCase();
            const motsClesLower = item.motsCles.map((mc) => mc.toLowerCase());
            return motsRecherche.some((mot) => {
                if (mot === "") return !1;
                const matchNom = nomLower.includes(mot);
                const matchMotCle = motsClesLower.some((mc) => mc.includes(mot));
                return matchNom || matchMotCle;
            });
        });
        afficherResultats(resultatsFiltres);
    });
    function afficherResultats(resultats) {
        listeResultats.innerHTML = "";
        if (resultats.length === 0) {
            zoneProposition.style.display = "none";
            return;
        }
        resultats.forEach((res) => {
            const li = document.createElement("li");
            const a = document.createElement("a");
            a.href = res.url;
            a.textContent = res.nom;
            li.appendChild(a);
            listeResultats.appendChild(li);
        });
        zoneProposition.style.display = "block";
    }
